"""Regenerate sw.js (the offline cache list and its version) after changing any app file.

Run from the gre-physics folder:  python3 tools/build-sw.py
The version is a hash of all cached files, so phones pick up the new version automatically.
"""
import hashlib
import os

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))

files = []
for root in ['js', 'vendor', 'icons']:
    for dirpath, _, names in os.walk(root):
        files += [os.path.join(dirpath, n) for n in names if not n.startswith('.')]
files = ['index.html', 'manifest.webmanifest', 'css/style.css'] + sorted(files)

h = hashlib.sha1()
for f in files:
    with open(f, 'rb') as fh:
        h.update(f.encode() + fh.read())
version = h.hexdigest()[:10]
listing = ',\n'.join(f"  '{f}'" for f in ['./'] + files)

with open('sw.js', 'w') as out:
    out.write(f"""/* Offline support: every file of the app is cached on first visit, so it keeps working
 * without a connection (and can be installed to a phone's home screen).
 * Cached copies are served immediately and refreshed in the background.
 * Generated by tools/build-sw.py: rerun it after changing any app file. */
const VERSION = '{version}';
const CACHE = 'gre-physics-' + VERSION;
const FILES = [
{listing},
];

self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('gre-physics-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async cache => {{
    const cached = await cache.match(e.request, {{ ignoreSearch: true }});
    const fresh = fetch(e.request).then(res => {{
      if (res.ok) cache.put(e.request, res.clone());
      return res;
    }}).catch(() => cached);
    return cached || fresh;
  }}));
}});
""")
print(f'sw.js: {len(files) + 1} files, version {version}')
